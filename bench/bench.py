#!/usr/bin/env python
"""One-shot benchmark: engine-level (in-process) then HTTP-level (through lily-serve).

    uv run python bench/bench.py --model-path CodeMan62/qwen3.8-27B-NVFP4A16
    uv run python bench/bench.py --model-path Qwen/Qwen3-0.6B --input-len 1024 --output-len 256 \
        --batch-sizes 1,8 --concurrency 1,4,8 -- --max-running-requests 16

Phase 1 (engine): builds `Engine` directly, random prompts of exactly --input-len
tokens, and times a batched prefill plus --decode-steps batched decode steps per
batch size. Reports prefill latency / throughput and median decode step latency /
throughput. No HTTP, tokenizer or scheduler in the loop.

Phase 2 (http): launches `lily-serve` as a subprocess, waits for /health, then
streams requests through the native /generate endpoint with exact `input_ids`
and `ignore_eos`. Output tokens come from the server's `completion_tokens`,
never from chunk counting. Reports, per concurrency level: request throughput,
output / total token throughput, TTFT, TPOT, ITL and end-to-end latency
(mean / median / p99), the same metrics `vllm bench serve` / `sglang.bench_serving`
print.

Anything after `--` is passed straight to `lily-serve` (phase 2 only).
Results are also written as JSON to --json (default bench/results/<model>-<time>.json).
Note -> code is generated by LLM
"""

from __future__ import annotations

import argparse
import asyncio
import gc
import json
import os
import random
import signal
import statistics
import subprocess
import sys
import time
from dataclasses import asdict, dataclass
from typing import Dict, List, Optional

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, ROOT)


# ---------------------------------------------------------------------------
# helpers
# ---------------------------------------------------------------------------

def _pct(xs: List[float], p: float) -> float:
    if not xs:
        return 0.0
    s = sorted(xs)
    return s[min(len(s) - 1, int(round(p / 100 * (len(s) - 1))))]


def _stats(xs: List[float]) -> Dict[str, float]:
    if not xs:
        return {"mean": 0.0, "median": 0.0, "p99": 0.0}
    return {"mean": statistics.fmean(xs), "median": statistics.median(xs), "p99": _pct(xs, 99)}


def _ms(d: Dict[str, float]) -> str:
    return f"{d['mean'] * 1000:.1f} / {d['median'] * 1000:.1f} / {d['p99'] * 1000:.1f}"


def _random_ids(n: int, vocab: int, seed: int) -> List[int]:
    rng = random.Random(seed)
    # stay clear of the lowest ids (special tokens) and the top of the vocab (unused slots)
    lo = min(100, max(0, vocab // 4))
    hi = max(lo + 1, min(vocab - 1, 50000))
    return [rng.randint(lo, hi) for _ in range(n)]


# ---------------------------------------------------------------------------
# phase 1: engine
# ---------------------------------------------------------------------------

@dataclass
class EngineRow:
    batch_size: int
    input_len: int
    prefill_ms: float
    prefill_tok_s: float
    decode_step_ms: float      # median
    decode_step_p99_ms: float
    decode_tok_s: float        # batch_size / median step


def bench_engine(args) -> List[EngineRow]:
    import torch

    from lily.engine import Engine, EngineConfig
    from lily.model_executor.forward_batch_info import ForwardBatch

    batch_sizes = sorted(set(args.batch_sizes))
    need_tokens = max(batch_sizes) * (args.input_len + args.decode_steps + 8)
    eng = Engine(EngineConfig(
        args.model_path, dtype=args.dtype,
        context_length=max(args.context_length or 0, args.input_len + args.decode_steps + 8),
        max_running_requests=max(batch_sizes),
        max_total_tokens=max(need_tokens, 4096),
    ))
    vocab = eng.model_config.vocab_size
    runner = eng.runner
    cap = runner.max_running_requests
    rows: List[EngineRow] = []

    def sync():
        torch.cuda.synchronize(eng.device)

    @torch.inference_mode()
    def run(bs: int) -> EngineRow:
        prompts = [_random_ids(args.input_len, vocab, seed=1000 + i) for i in range(bs)]
        idxs = [eng._new_seq() for _ in range(bs)]
        seq_lens = [0] * bs
        try:
            # ---- prefill ----
            locs = torch.cat([eng._alloc(idxs[i], 0, args.input_len) for i in range(bs)])
            fb = ForwardBatch.for_extend(prompts, [0] * bs, idxs, eng.device, out_cache_loc=locs)
            sync(); t0 = time.perf_counter()
            out = runner.forward(fb)
            sync(); prefill = time.perf_counter() - t0
            seq_lens = [args.input_len] * bs
            toks = [int(t) for t in torch.argmax(out.next_token_logits, dim=-1)]

            # ---- decode ----
            step_times: List[float] = []
            for step in range(args.decode_steps + args.decode_warmup):
                locs = torch.cat([eng._alloc(idxs[i], seq_lens[i], 1) for i in range(bs)])
                fb = ForwardBatch.for_decode(toks, [s + 1 for s in seq_lens], idxs, eng.device, out_cache_loc=locs)
                sync(); t0 = time.perf_counter()
                out = runner.forward(fb)
                sync(); dt = time.perf_counter() - t0
                seq_lens = [s + 1 for s in seq_lens]
                toks = [int(t) for t in torch.argmax(out.next_token_logits, dim=-1)]
                if step >= args.decode_warmup:
                    step_times.append(dt)
        finally:
            for i in range(bs):
                eng._release(idxs[i], seq_lens[i])
        med = statistics.median(step_times)
        return EngineRow(bs, args.input_len, prefill * 1000, bs * args.input_len / prefill,
                         med * 1000, _pct(step_times, 99) * 1000, bs / med)

    # warmup: triton compile / cuda graph capture happen here, not inside the timed run
    run(1)
    for bs in batch_sizes:
        if bs > cap:
            print(f"  skipping batch size {bs}: engine capped max_running_requests at {cap}", flush=True)
            continue
        rows.append(run(bs))
        print("  " + _engine_line(rows[-1]), flush=True)

    del eng, runner
    gc.collect()
    torch.cuda.empty_cache()
    return rows


def _engine_line(r: EngineRow) -> str:
    return (f"bs={r.batch_size:<3d} prefill {r.prefill_ms:8.1f} ms ({r.prefill_tok_s:9.0f} tok/s)   "
            f"decode step {r.decode_step_ms:7.2f} ms median / {r.decode_step_p99_ms:7.2f} p99 "
            f"({r.decode_tok_s:7.1f} tok/s)")


def engine_table(rows: List[EngineRow]) -> str:
    out = ["| batch | prefill ms | prefill tok/s | decode step ms (median / p99) | decode tok/s |",
           "|---|---|---|---|---|"]
    for r in rows:
        out.append(f"| {r.batch_size} | {r.prefill_ms:.1f} | {r.prefill_tok_s:.0f} | "
                   f"{r.decode_step_ms:.2f} / {r.decode_step_p99_ms:.2f} | {r.decode_tok_s:.1f} |")
    return "\n".join(out)


# ---------------------------------------------------------------------------
# phase 2: http
# ---------------------------------------------------------------------------

@dataclass
class ReqResult:
    ok: bool
    prompt_tokens: int
    output_tokens: int
    ttft: float            # s, first chunk carrying >= 1 completion token
    latency: float         # s, end to end
    itl: List[float]       # s, gaps between successive token-carrying chunks
    error: str = ""


async def _one_request(client, url: str, input_ids: List[int], output_len: int) -> ReqResult:
    import httpx  # noqa: F401  (type only)

    body = {
        "input_ids": input_ids, "stream": True,
        "sampling_params": {"max_new_tokens": output_len, "ignore_eos": True, "temperature": 0.0},
    }
    t0 = time.perf_counter()
    ttft: Optional[float] = None
    last_t = t0
    itl: List[float] = []
    prompt_tokens = len(input_ids)
    completion = 0
    try:
        async with client.stream("POST", url, json=body, timeout=None) as resp:
            if resp.status_code != 200:
                return ReqResult(False, prompt_tokens, 0, 0.0, 0.0, [], f"HTTP {resp.status_code}")
            async for line in resp.aiter_lines():
                if not line.startswith("data: "):
                    continue
                payload = line[6:]
                if payload == "[DONE]":
                    break
                chunk = json.loads(payload)
                meta = chunk.get("meta_info", {})
                n = int(meta.get("completion_tokens", completion))
                now = time.perf_counter()
                if n > completion:
                    if ttft is None:
                        ttft = now - t0
                    else:
                        itl.append(now - last_t)
                    last_t = now
                    completion = n
                prompt_tokens = int(meta.get("prompt_tokens", prompt_tokens))
                if "finish_reason" in meta:
                    break
    except Exception as e:  # noqa: BLE001
        return ReqResult(False, prompt_tokens, completion, ttft or 0.0, time.perf_counter() - t0, itl, repr(e))
    latency = time.perf_counter() - t0
    if ttft is None:
        return ReqResult(False, prompt_tokens, completion, 0.0, latency, itl, "no tokens received")
    return ReqResult(True, prompt_tokens, completion, ttft, latency, itl)


@dataclass
class HttpRow:
    concurrency: int
    num_requests: int
    failed: int
    duration_s: float
    req_s: float
    output_tok_s: float
    total_tok_s: float
    ttft: Dict[str, float]
    tpot: Dict[str, float]
    itl: Dict[str, float]
    latency: Dict[str, float]


async def _sweep_level(client, url: str, prompts: List[List[int]], output_len: int, concurrency: int) -> HttpRow:
    sem = asyncio.Semaphore(concurrency)

    async def guarded(ids):
        async with sem:
            return await _one_request(client, url, ids, output_len)

    t0 = time.perf_counter()
    results: List[ReqResult] = await asyncio.gather(*(guarded(p) for p in prompts))
    dur = time.perf_counter() - t0
    ok = [r for r in results if r.ok]
    out_toks = sum(r.output_tokens for r in ok)
    in_toks = sum(r.prompt_tokens for r in ok)
    tpot = [(r.latency - r.ttft) / (r.output_tokens - 1) for r in ok if r.output_tokens > 1]
    itl = [x for r in ok for x in r.itl]
    for r in results:
        if not r.ok:
            print(f"    request failed: {r.error}", flush=True)
    return HttpRow(
        concurrency=concurrency, num_requests=len(results), failed=len(results) - len(ok), duration_s=dur,
        req_s=len(ok) / dur, output_tok_s=out_toks / dur, total_tok_s=(in_toks + out_toks) / dur,
        ttft=_stats([r.ttft for r in ok]), tpot=_stats(tpot), itl=_stats(itl),
        latency=_stats([r.latency for r in ok]),
    )


def _wait_health(proc: subprocess.Popen, base: str, log_path: str, timeout: float) -> None:
    import httpx

    t0 = time.time()
    while True:
        if proc.poll() is not None:
            raise RuntimeError(f"lily-serve exited with {proc.returncode}; see {log_path}")
        try:
            if httpx.get(f"{base}/health", timeout=2.0).status_code == 200:
                return
        except Exception:  # noqa: BLE001
            pass
        with open(log_path, errors="replace") as f:
            if "Traceback" in f.read():
                raise RuntimeError(f"lily-serve crashed during startup; see {log_path}")
        if time.time() - t0 > timeout:
            raise RuntimeError(f"lily-serve not healthy after {timeout:.0f}s; see {log_path}")
        time.sleep(1.0)


def bench_http(args, serve_args: List[str]) -> List[HttpRow]:
    import httpx
    from transformers import AutoConfig

    base = f"http://127.0.0.1:{args.port}"
    log_path = os.path.join(args.log_dir, f"lily-serve-{int(time.time())}.log")
    os.makedirs(args.log_dir, exist_ok=True)
    cmd = ["uv", "run", "lily-serve", "--model-path", args.model_path, "--dtype", args.dtype,
           "--port", str(args.port), "--disable-overlap-schedule", *serve_args]
    print(f"  launching: {' '.join(cmd)}\n  log: {log_path}", flush=True)
    log = open(log_path, "wb")
    proc = subprocess.Popen(cmd, stdout=log, stderr=subprocess.STDOUT, cwd=ROOT, start_new_session=True)
    try:
        _wait_health(proc, base, log_path, args.startup_timeout)
        cfg = AutoConfig.from_pretrained(args.model_path, trust_remote_code=True)
        text = getattr(cfg, "text_config", cfg)
        vocab = int(getattr(text, "vocab_size", getattr(cfg, "vocab_size", 32000)))
        url = f"{base}/generate"
        rows: List[HttpRow] = []

        async def go():
            async with httpx.AsyncClient() as client:
                # warmup, excluded from the numbers
                await _one_request(client, url, _random_ids(args.input_len, vocab, seed=7), args.output_len)
                for c in args.concurrency:
                    n = max(args.num_prompts, c)
                    prompts = [_random_ids(args.input_len, vocab, seed=10_000 + i) for i in range(n)]
                    row = await _sweep_level(client, url, prompts, args.output_len, c)
                    rows.append(row)
                    print("  " + _http_line(row), flush=True)

        asyncio.run(go())
        return rows
    finally:
        try:
            os.killpg(os.getpgid(proc.pid), signal.SIGKILL)  # uvicorn ignores SIGTERM with in-flight streams
        except ProcessLookupError:
            pass
        log.close()


def _http_line(r: HttpRow) -> str:
    return (f"conc={r.concurrency:<3d} {r.output_tok_s:8.1f} out tok/s  {r.req_s:6.2f} req/s  "
            f"ttft {r.ttft['median'] * 1000:7.1f} ms  tpot {r.tpot['median'] * 1000:6.2f} ms  "
            f"e2e {r.latency['median']:6.2f} s" + (f"  FAILED {r.failed}" if r.failed else ""))


def http_table(rows: List[HttpRow]) -> str:
    out = ["| conc | reqs | req/s | output tok/s | total tok/s | ttft ms (mean/med/p99) | "
           "tpot ms (mean/med/p99) | itl ms (mean/med/p99) | e2e s (mean/med/p99) |",
           "|---|---|---|---|---|---|---|---|---|"]
    for r in rows:
        lat = r.latency
        out.append(f"| {r.concurrency} | {r.num_requests - r.failed}/{r.num_requests} | {r.req_s:.2f} | "
                   f"{r.output_tok_s:.1f} | {r.total_tok_s:.1f} | {_ms(r.ttft)} | {_ms(r.tpot)} | {_ms(r.itl)} | "
                   f"{lat['mean']:.2f} / {lat['median']:.2f} / {lat['p99']:.2f} |")
    return "\n".join(out)


# ---------------------------------------------------------------------------
# main
# ---------------------------------------------------------------------------

def _int_list(s: str) -> List[int]:
    return [int(x) for x in s.split(",") if x.strip()]


def main(argv=None) -> None:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--model-path", required=True)
    ap.add_argument("--dtype", default="bfloat16")
    ap.add_argument("--input-len", type=int, default=512)
    ap.add_argument("--output-len", type=int, default=128, help="http phase: tokens generated per request")
    ap.add_argument("--context-length", type=int, default=None)
    # engine phase
    ap.add_argument("--batch-sizes", type=_int_list, default=[1, 2, 4, 8])
    ap.add_argument("--decode-steps", type=int, default=32, help="timed decode steps per batch size")
    ap.add_argument("--decode-warmup", type=int, default=4)
    # http phase
    ap.add_argument("--concurrency", type=_int_list, default=[1, 2, 4, 8])
    ap.add_argument("--num-prompts", type=int, default=8, help="requests per concurrency level (>= concurrency)")
    ap.add_argument("--port", type=int, default=30000)
    ap.add_argument("--startup-timeout", type=float, default=1800)
    ap.add_argument("--log-dir", default=os.path.join(ROOT, "bench", "logs"))
    ap.add_argument("--skip-engine", action="store_true")
    ap.add_argument("--skip-http", action="store_true")
    ap.add_argument("--json", default=None, help="results file (default bench/results/<model>-<time>.json)")
    args, serve_args = ap.parse_known_args(argv)
    if serve_args and serve_args[0] == "--":
        serve_args = serve_args[1:]

    results: Dict = {"model": args.model_path, "dtype": args.dtype, "input_len": args.input_len,
                     "output_len": args.output_len, "engine": [], "http": []}
    t_all = time.time()

    if not args.skip_engine:
        print(f"\n== engine phase: {args.model_path}  input_len={args.input_len}  "
              f"decode_steps={args.decode_steps}", flush=True)
        results["engine"] = [asdict(r) for r in bench_engine(args)]

    if not args.skip_http:
        print(f"\n== http phase: {args.model_path}  input_len={args.input_len}  output_len={args.output_len}",
              flush=True)
        results["http"] = [asdict(r) for r in bench_http(args, serve_args)]

    print(f"\n# {args.model_path}  ({args.dtype}, {args.input_len} in / {args.output_len} out, "
          f"{time.time() - t_all:.0f}s total)\n")
    if results["engine"]:
        print("## engine (in-process, no HTTP)\n")
        print(engine_table([EngineRow(**r) for r in results["engine"]]) + "\n")
    if results["http"]:
        print("## http (lily-serve, streaming /generate)\n")
        print(http_table([HttpRow(**r) for r in results["http"]]) + "\n")

    path = args.json or os.path.join(ROOT, "bench", "results",
                                     f"{args.model_path.replace('/', '_')}-{int(t_all)}.json")
    os.makedirs(os.path.dirname(path), exist_ok=True)
    with open(path, "w") as f:
        json.dump(results, f, indent=1)
    print(f"json: {path}")


if __name__ == "__main__":
    main()
